export const ALTURA = 7;
export const LINHA = 11;

const largura = (g: string[]) => g[0].length;

const glifo = (ch: string): { g: string[]; acento?: string[]; cedilha?: boolean } => {
  if (G[ch]) return { g: G[ch] };
  if (ACENTO[ch]) return { g: G[ACENTO[ch][0]], acento: ACENTO[ch][1] };
  if (ch === "Ç") return { g: G.C, cedilha: true };
  return { g: G["?"] };
};

export const normalizar = (s: string) => s.toUpperCase();

export const medir = (texto: string, escala = 1) => {
  let w = 0;
  for (const ch of normalizar(texto)) w += (largura(glifo(ch).g) + 1) * escala;
  return Math.max(0, w - escala);
};

export type OptTexto = {
  escala?: number;
  cor?: RGB;
  contorno?: RGB | null; // contorno de 1 px em volta (legibilidade)
  sombra?: RGB | null; // sombra 1 px para baixo/direita
  alfa?: number;
  max?: number; // nº de caracteres visíveis (texto letra por letra)
};

/** desenha texto; devolve a largura */
export const texto = (b: Buf, s: string, x: number, y: number, o: OptTexto = {}) => {
  const k = o.escala ?? 1;
  const cor = o.cor ?? [255, 255, 255];
  const a = o.alfa ?? 1;
  const str = normalizar(s);
  const max = o.max ?? Infinity;
  const pontos: [number, number][] = [];
  let cx = Math.round(x);
  let n = 0;
  for (const ch of str) {
    if (n >= max) break;
    n++;
    const { g, acento, cedilha } = glifo(ch);
    const w = largura(g);
    const marcar = (gx: number, gy: number) => {
      for (let yy = 0; yy < k; yy++) for (let xx = 0; xx < k; xx++) pontos.push([cx + gx * k + xx, Math.round(y) + gy * k + yy]);
    };
    g.forEach((linha, gy) => linha.split("").forEach((c, gx) => c === "#" && marcar(gx, gy)));
    if (acento) acento.forEach((linha, gy) => linha.split("").forEach((c, gx) => c === "#" && marcar(gx, gy - 3)));
    if (cedilha) {
      marcar(2, 7);
      marcar(1, 8);
      marcar(2, 8);
    }
    cx += (w + 1) * k;
  }
  if (o.contorno) {
    const set = new Set(pontos.map(([px0, py0]) => py0 * 4096 + px0));
    for (const [px0, py0] of pontos)
      for (let dy = -1; dy <= 1; dy++)
        for (let dx = -1; dx <= 1; dx++) {
          const xx = px0 + dx;
          const yy = py0 + dy;
          if (!set.has(yy * 4096 + xx)) px(b, xx, yy, o.contorno, a);
        }
  }
  if (o.sombra) for (const [px0, py0] of pontos) px(b, px0 + 1, py0 + 1, o.sombra, a * 0.8);
  for (const [px0, py0] of pontos) px(b, px0, py0, cor, a);
  return cx - Math.round(x) - k;
};

export const textoCentro = (b: Buf, s: string, cx: number, y: number, o: OptTexto = {}) =>
  texto(b, s, Math.round(cx - medir(s, o.escala ?? 1) / 2), y, o);

/** quebra em linhas que cabem em `max` px */
export const quebrar = (s: string, max: number, escala = 1): string[] => {
  const palavras = s.split(/\s+/);
  const linhas: string[] = [];
  let atual = "";
  for (const p of palavras) {
    const tentativa = atual ? atual + " " + p : p;
    if (medir(tentativa, escala) > max && atual) {
      linhas.push(atual);
      atual = p;
    } else atual = tentativa;
  }
  if (atual) linhas.push(atual);
  return linhas;
};
